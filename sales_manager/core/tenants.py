"""Several businesses in one app and one PostgreSQL database, each in its own schema.

The directory (schema `nirkana_operador`) lists the businesses: their code (used in the address, `?negocio=code`),
name, status and the one-time setup code that lets the business create its first administrator. Each business's
data lives in schema `n_<code>`, created with the same tables as a single-business database, so nothing a business
does can read or change another's data: every query runs with its own schema as the search path.
"""

import json
import re
import secrets
import time
from datetime import datetime, timedelta

from . import clock, logs
from .billing import (LIVE, PAID, TRIAL_DAYS, Access, BillingError, access, best_subscription, parse_when,
                      subscription_fields, utc_now)
from .db import Store
from .engines import secure_url, acquire_pool, release_pool
from .throttle import after_failure, blocked_minutes, key_hash
from .security import hash_secret, is_safe_identifier, verify_secret

DIRECTORY_SCHEMA = "nirkana_operador"
log = logs.get("tenants")
CODE_RE = re.compile(r"[a-z0-9](?:[a-z0-9-]{1,38}[a-z0-9])")
STATUSES = {"activo": "Activo", "suspendido": "Suspendido"}
TENANT_FIELDS = ("code, name, schema_name, status, contact, created_at, setup_used_at, billing_status, trial_ends, "
                 "period_end, cancel_at_period_end, stripe_customer, stripe_subscription, billing_exempt, "
                 "billing_synced_at, billing_event_at")
RESERVED = {"operador", "admin", "www", "app", "api", "nirkana"}

DIRECTORY_SQL = f"""
CREATE SCHEMA IF NOT EXISTS {DIRECTORY_SCHEMA};
CREATE TABLE IF NOT EXISTS {DIRECTORY_SCHEMA}.tenants (
    code TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    schema_name TEXT UNIQUE NOT NULL,
    status TEXT NOT NULL DEFAULT 'activo',
    contact TEXT NOT NULL DEFAULT '',
    setup_hash TEXT NOT NULL DEFAULT '',
    setup_used_at TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL
);
ALTER TABLE {DIRECTORY_SCHEMA}.tenants ADD COLUMN IF NOT EXISTS billing_status TEXT NOT NULL DEFAULT 'prueba';
ALTER TABLE {DIRECTORY_SCHEMA}.tenants ADD COLUMN IF NOT EXISTS trial_ends TEXT NOT NULL DEFAULT '';
ALTER TABLE {DIRECTORY_SCHEMA}.tenants ADD COLUMN IF NOT EXISTS period_end TEXT NOT NULL DEFAULT '';
ALTER TABLE {DIRECTORY_SCHEMA}.tenants ADD COLUMN IF NOT EXISTS cancel_at_period_end INTEGER NOT NULL DEFAULT 0;
ALTER TABLE {DIRECTORY_SCHEMA}.tenants ADD COLUMN IF NOT EXISTS stripe_customer TEXT NOT NULL DEFAULT '';
ALTER TABLE {DIRECTORY_SCHEMA}.tenants ADD COLUMN IF NOT EXISTS stripe_subscription TEXT NOT NULL DEFAULT '';
ALTER TABLE {DIRECTORY_SCHEMA}.tenants ADD COLUMN IF NOT EXISTS billing_exempt INTEGER NOT NULL DEFAULT 0;
ALTER TABLE {DIRECTORY_SCHEMA}.tenants ADD COLUMN IF NOT EXISTS billing_synced_at TEXT NOT NULL DEFAULT '';
ALTER TABLE {DIRECTORY_SCHEMA}.tenants ADD COLUMN IF NOT EXISTS billing_event_at BIGINT NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS {DIRECTORY_SCHEMA}.stripe_events (
    id TEXT PRIMARY KEY,
    type TEXT NOT NULL,
    received_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS {DIRECTORY_SCHEMA}.operator_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    happened_at TEXT NOT NULL,
    action TEXT NOT NULL,
    detail TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS {DIRECTORY_SCHEMA}.operator_totp (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    last_step BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS {DIRECTORY_SCHEMA}.login_throttle (
    key TEXT PRIMARY KEY,
    fails TEXT NOT NULL DEFAULT '[]',
    blocked_until BIGINT NOT NULL DEFAULT 0,
    level INTEGER NOT NULL DEFAULT 0,
    updated BIGINT NOT NULL DEFAULT 0
)
"""
# Billing is re-checked with Stripe this often, in case a webhook was lost.
SYNC_EVERY = timedelta(hours=6)
EVENTS_KEPT_DAYS = 90
# Payments that went back to the customer: Stripe does not end the subscription for them, so the operator is told.
MONEY_BACK = {"charge.refunded": "reembolso", "charge.dispute.created": "contracargo_abierto",
              "charge.dispute.closed": "contracargo_cerrado"}


class AlreadySubscribed(BillingError):
    """The business already has a subscription in Stripe: it is managed in the portal, not bought again."""


def _stripe_id(value) -> str:
    """Stripe sends a related object either as its id or, expanded, as the object itself."""
    return str((value.get("id") if isinstance(value, dict) else value) or "")


def normalize_code(value: str) -> str:
    return str(value or "").strip().lower()


def schema_for(code: str) -> str:
    return "n_" + code.replace("-", "_")


class Directory:
    """The list of businesses served by one database. Only the operator creates, suspends or lists them."""

    def __init__(self, url: str):
        self._url = secure_url(url)
        # The same pool as the businesses' stores on this database, instead of a new connection per call.
        self._pool_key, pool = acquire_pool(url)
        self._connect = pool.connection
        with self._connect() as conn:
            for statement in filter(str.strip, DIRECTORY_SQL.split(";")):
                conn.execute(statement)
            # Businesses from before billing: their free trial starts the day billing arrives, not at their sign-up.
            conn.execute(f"UPDATE {DIRECTORY_SCHEMA}.tenants SET trial_ends = %s WHERE trial_ends = ''",
                         ((utc_now() + timedelta(days=TRIAL_DAYS)).isoformat(timespec="seconds"),))
            # Stripe stops retrying an event after three days: ids older than that are never needed again.
            conn.execute(f"DELETE FROM {DIRECTORY_SCHEMA}.stripe_events WHERE received_at < %s",
                         ((utc_now() - timedelta(days=EVENTS_KEPT_DAYS)).isoformat(timespec="seconds"),))

    def _log(self, conn, action: str, detail: str = "") -> None:
        conn.execute(f"INSERT INTO {DIRECTORY_SCHEMA}.operator_log(happened_at, action, detail) VALUES (%s, %s, %s)",
                     (clock.now().isoformat(timespec="seconds"), action, detail[:300]))

    # ------------------------------------------------------------------ businesses
    def get(self, code: str) -> dict | None:
        code = normalize_code(code)
        if not CODE_RE.fullmatch(code):
            return None
        with self._connect() as conn:
            return conn.execute(f"SELECT {TENANT_FIELDS} FROM {DIRECTORY_SCHEMA}.tenants WHERE code = %s",
                                (code,)).fetchone()

    def create(self, code: str, name: str, contact: str = "", trial_days: int = TRIAL_DAYS) -> str:
        """Create a business with its own schema and tables. Returns its one-time setup code (shown only once)."""
        code = normalize_code(code)
        if not CODE_RE.fullmatch(code) or "--" in code:
            raise ValueError("El código debe tener de 3 a 40 letras minúsculas, números o guiones (p. ej. cafe-aurora).")
        if code in RESERVED:
            raise ValueError("Ese código está reservado. Elige otro.")
        name = str(name or "").strip()[:120]
        if not name:
            raise ValueError("Escribe el nombre del negocio.")
        if self.get(code):
            raise ValueError("Ya existe un negocio con ese código.")
        schema = schema_for(code)
        setup = secrets.token_hex(4).upper()
        with self._connect() as conn:
            conn.execute(f'CREATE SCHEMA IF NOT EXISTS "{schema}"')
        store = Store(self._url, schema=schema)  # creates every table of a business in its schema
        try:
            store.save_settings({"business_name": name})
        finally:
            store.close()
        with self._connect() as conn:
            trial_ends = (utc_now() + timedelta(days=int(trial_days))).isoformat(timespec="seconds")
            conn.execute(f"INSERT INTO {DIRECTORY_SCHEMA}.tenants(code, name, schema_name, contact, setup_hash, "
                         "created_at, trial_ends) VALUES (%s, %s, %s, %s, %s, %s, %s)",
                         (code, name, schema, str(contact or "")[:200], hash_secret(setup),
                          clock.now().isoformat(timespec="seconds"), trial_ends))
            self._log(conn, "negocio_creado", f"{code} · {name}")
        return setup

    def check_setup_code(self, code: str, setup: str) -> bool:
        """The business's one-time code for creating its first administrator."""
        with self._connect() as conn:
            row = conn.execute(f"SELECT setup_hash, setup_used_at FROM {DIRECTORY_SCHEMA}.tenants WHERE code = %s",
                               (normalize_code(code),)).fetchone()
        return bool(row and row["setup_hash"] and not row["setup_used_at"]
                    and verify_secret(str(setup or "").strip().upper(), row["setup_hash"]))

    def mark_setup_used(self, code: str) -> None:
        with self._connect() as conn:
            conn.execute(f"UPDATE {DIRECTORY_SCHEMA}.tenants SET setup_used_at = %s WHERE code = %s",
                         (clock.now().isoformat(timespec="seconds"), normalize_code(code)))
            self._log(conn, "administrador_creado", normalize_code(code))

    def new_setup_code(self, code: str) -> str:
        """A fresh one-time code, e.g. when the business lost it before creating its administrator."""
        setup = secrets.token_hex(4).upper()
        with self._connect() as conn:
            updated = conn.execute(f"UPDATE {DIRECTORY_SCHEMA}.tenants SET setup_hash = %s, setup_used_at = '' "
                                   "WHERE code = %s", (hash_secret(setup), normalize_code(code))).rowcount
            if not updated:
                raise ValueError("Negocio no encontrado.")
            self._log(conn, "codigo_instalacion_nuevo", normalize_code(code))
        return setup

    def set_status(self, code: str, status: str) -> None:
        if status not in STATUSES:
            raise ValueError("Estado no válido.")
        with self._connect() as conn:
            updated = conn.execute(f"UPDATE {DIRECTORY_SCHEMA}.tenants SET status = %s WHERE code = %s",
                                   (status, normalize_code(code))).rowcount
            if not updated:
                raise ValueError("Negocio no encontrado.")
            self._log(conn, f"negocio_{status}", normalize_code(code))

    def overview(self) -> list[dict]:
        """Every business with its activity, for the operator panel: three round trips in all, whatever the number
        of businesses (it used to be four queries per business)."""
        since = (clock.now() - timedelta(days=7)).isoformat(timespec="seconds")
        with self._connect() as conn:
            tenants = conn.execute(f"SELECT {TENANT_FIELDS} FROM {DIRECTORY_SCHEMA}.tenants "
                                   "ORDER BY created_at").fetchall()
            if not tenants:
                return tenants
            schemas = [t["schema_name"] for t in tenants]
            ready = {r["schema"]: set(r["tables"]) for r in conn.execute(
                "SELECT table_schema AS schema, array_agg(table_name::text) AS tables FROM information_schema.tables "
                "WHERE table_schema = ANY(%s) AND table_name IN ('sales', 'users', 'app_errors') "
                "GROUP BY table_schema", (schemas,)).fetchall()}
            parts, params = [], []
            for schema in schemas:
                tables = ready.get(schema, set())
                if not is_safe_identifier(schema) or not {"sales", "users"} <= tables:
                    continue  # never set up (or not yet): shown with zeros
                errors = (f'(SELECT COUNT(*) FROM "{schema}".app_errors WHERE happened_at >= %s)'
                          if "app_errors" in tables else "0")
                parts.append(f'SELECT %s AS schema, (SELECT COUNT(*) FROM "{schema}".sales) AS sales, '
                             f'(SELECT MAX(created_at) FROM "{schema}".sales) AS last_sale, '
                             f'(SELECT COUNT(*) FROM "{schema}".users WHERE active = 1) AS users, {errors} AS errors')
                params += [schema] + ([since] if "app_errors" in tables else [])
            stats = {r["schema"]: r for r in conn.execute(" UNION ALL ".join(parts), params).fetchall()} if parts else {}
        for t in tenants:
            row = stats.get(t["schema_name"]) or {}
            t.update(sales=int(row.get("sales") or 0), last_sale=row.get("last_sale") or "",
                     users=int(row.get("users") or 0), errors=int(row.get("errors") or 0))
        return tenants

    # ------------------------------------------------------------------ billing
    def _billing_update(self, conn, code: str, fields: dict, action: str) -> bool:
        allowed = {"billing_status", "trial_ends", "period_end", "cancel_at_period_end", "stripe_customer",
                   "stripe_subscription", "billing_exempt", "billing_event_at"}
        fields = {k: v for k, v in fields.items() if k in allowed}
        fields["billing_synced_at"] = utc_now().isoformat(timespec="seconds")
        sets = ", ".join(f"{k} = %s" for k in fields)
        updated = conn.execute(f"UPDATE {DIRECTORY_SCHEMA}.tenants SET {sets} WHERE code = %s",
                               (*fields.values(), normalize_code(code))).rowcount
        if updated and action:
            self._log(conn, action, f"{normalize_code(code)} · {fields.get('billing_status', '')}".strip(" ·"))
        return bool(updated)

    def _locked(self, conn, code: str) -> dict | None:
        """The business's row, locked until the transaction ends: two notices about it are applied one after the
        other, never interleaved."""
        code = normalize_code(code)
        if not CODE_RE.fullmatch(code):
            return None
        return conn.execute(f"SELECT {TENANT_FIELDS} FROM {DIRECTORY_SCHEMA}.tenants WHERE code = %s FOR UPDATE",
                            (code,)).fetchone()

    def _record(self, conn, tenant: dict, subscription: dict, action: str, event_at: int = 0) -> bool:
        """Keep one subscription as a notice reports it. A notice only shows that subscription, so it may not replace
        a paid one by one that is not (an older attempt, or a duplicate being cancelled)."""
        current, new_id = tenant["stripe_subscription"], subscription.get("id")
        if current and new_id != current and tenant["billing_status"] in PAID:
            if subscription.get("status") not in PAID:
                return False
            self._duplicate(conn, tenant["code"], [current, new_id], action)
        fields = subscription_fields(subscription)
        if event_at:
            fields["billing_event_at"] = max(int(event_at), int(tenant["billing_event_at"] or 0))
        return self._billing_update(conn, tenant["code"], fields, action)

    def _record_live(self, conn, tenant: dict, subscriptions: list[dict], action: str) -> bool:
        """Keep what Stripe has now for the business's customer: all its subscriptions, so the one that decides
        access is chosen knowing every other (see best_subscription)."""
        paid = [s.get("id") for s in subscriptions if s.get("status") in PAID]
        if len(paid) > 1:
            self._duplicate(conn, tenant["code"], paid, action)
        best = best_subscription(subscriptions)
        return self._billing_update(conn, tenant["code"], subscription_fields(best) if best else {}, action)

    def _duplicate(self, conn, code: str, ids: list, action: str) -> None:
        """Two subscriptions charging one business: the operator cancels and refunds one in Stripe."""
        log.warning("billing_duplicate_subscription tenant=%s subscriptions=%s", code, ",".join(map(str, ids)))
        if action:
            self._log(conn, "suscripcion_duplicada", f"{code} · " + ", ".join(map(str, ids)))

    def _code_for_customer(self, conn, customer: str) -> str | None:
        if not customer:
            return None
        row = conn.execute(f"SELECT code FROM {DIRECTORY_SCHEMA}.tenants WHERE stripe_customer = %s",
                           (customer,)).fetchone()
        return row["code"] if row else None

    def record_subscription(self, code: str, subscription: dict, action: str = "suscripcion_actualizada") -> bool:
        """Keep a business's subscription as Stripe reports it."""
        with self._connect() as conn:
            tenant = self._locked(conn, code)
            return bool(tenant) and self._record(conn, tenant, subscription, action)

    def set_billing_exempt(self, code: str, exempt: bool) -> None:
        """Businesses that use the service free of charge (pilots, friends): never asked to pay."""
        with self._connect() as conn:
            if not self._billing_update(conn, code, {"billing_exempt": int(bool(exempt))}, ""):
                raise ValueError("Negocio no encontrado.")
            self._log(conn, "cortesia_activada" if exempt else "cortesia_retirada", normalize_code(code))

    def extend_trial(self, code: str, days: int) -> None:
        tenant = self.get(code)
        if tenant is None:
            raise ValueError("Negocio no encontrado.")
        if not 1 <= int(days) <= 365:
            raise ValueError("Amplía entre 1 y 365 días.")
        start = max(utc_now(), datetime.fromisoformat(tenant["trial_ends"]) if tenant["trial_ends"] else utc_now())
        with self._connect() as conn:
            self._billing_update(conn, code, {"trial_ends": (start + timedelta(days=int(days))).isoformat(
                timespec="seconds")}, "")
            self._log(conn, "prueba_ampliada", f"{normalize_code(code)} · {int(days)} días")

    def process_event(self, event: dict, stripe=None) -> str:
        """Apply a (signature-checked) Stripe event once. Returns what was done, for the log and tests.

        The event is marked as received in the same transaction that applies it: if applying fails, nothing is
        kept, the webhook answers with an error and Stripe's retry is applied instead of being taken for a repeat.
        With `stripe`, subscription notices are a cue to ask Stripe for the customer's subscriptions as they are now,
        so notices arriving late or out of order cannot bring back an old state."""
        with self._connect() as conn:
            fresh = conn.execute(f"INSERT INTO {DIRECTORY_SCHEMA}.stripe_events(id, type, received_at) "
                                 "VALUES (%s, %s, %s) ON CONFLICT (id) DO NOTHING",
                                 (event["id"], str(event.get("type", ""))[:80],
                                  utc_now().isoformat(timespec="seconds"))).rowcount
            if not fresh:
                return "repetido"
            return self._apply_event(conn, event, stripe)

    def _apply_event(self, conn, event: dict, stripe) -> str:
        kind = event.get("type", "")
        obj = (event.get("data") or {}).get("object") or {}
        customer = _stripe_id(obj.get("customer"))
        if kind == "checkout.session.completed":
            code = obj.get("client_reference_id") or (obj.get("metadata") or {}).get("tenant")
            tenant = self._locked(conn, code) if code else None
            if tenant is None:
                return "ignorado"
            subscription = obj.get("subscription")
            if stripe is not None and customer:
                self._billing_update(conn, tenant["code"], {"stripe_customer": customer}, "")
                self._record_live(conn, tenant, stripe.subscriptions(customer), "suscripcion_contratada")
            elif isinstance(subscription, dict):
                self._record(conn, tenant, subscription, "suscripcion_contratada")
            else:  # not expanded: link the customer now; the subscription's own event (any order) brings its state
                self._billing_update(conn, tenant["code"], {"stripe_customer": customer,
                                                            "stripe_subscription": subscription or ""},
                                     "suscripcion_contratada")
            return "vinculado"
        if kind.startswith("customer.subscription."):
            code = (obj.get("metadata") or {}).get("tenant") or self._code_for_customer(conn, customer)
            tenant = self._locked(conn, code) if code else None
            if tenant is None:
                return "ignorado"
            action = "suscripcion_" + kind.rsplit(".", 1)[-1]
            if stripe is not None and customer:
                self._record_live(conn, tenant, stripe.subscriptions(customer), action)
                return "actualizado"
            created = int(event.get("created") or 0)
            if created and created < int(tenant["billing_event_at"] or 0):
                return "antiguo"  # Stripe does not deliver in order: a later state was already applied
            self._record(conn, tenant, obj, action, event_at=created)
            return "actualizado"
        if kind in MONEY_BACK:
            if not customer and stripe is not None and obj.get("charge"):
                customer = stripe.charge_customer(_stripe_id(obj["charge"]))
            code = self._code_for_customer(conn, customer) or "?"
            cents = obj.get("amount_refunded") if kind == "charge.refunded" else obj.get("amount")
            detail = " · ".join(str(x) for x in (
                code, _stripe_id(obj.get("charge")) or obj.get("id", ""),
                f"{int(cents or 0) / 100:.2f} {str(obj.get('currency', '')).upper()}".strip(),
                obj.get("reason") or "", obj.get("status") if kind != "charge.refunded" else "") if x)
            self._log(conn, MONEY_BACK[kind], detail)
            log.warning("billing_money_back type=%s tenant=%s", kind, code)
            return "registrado"
        return "ignorado"

    def sync_subscription(self, code: str, stripe) -> dict | None:
        """Ask Stripe for a business's subscriptions (safety net for lost webhooks)."""
        tenant = self.get(code)
        if tenant is None or not tenant["stripe_customer"]:
            return tenant
        subscriptions = stripe.subscriptions(tenant["stripe_customer"])
        with self._connect() as conn:
            tenant = self._locked(conn, code)
            if tenant is not None:
                self._record_live(conn, tenant, subscriptions, "")
        return self.get(code)

    def checkout_url(self, code: str, stripe, email: str, success_url: str, cancel_url: str) -> str:
        """Stripe Checkout for a business that has no subscription. Asks Stripe first, not a copy that may be
        minutes old, so a business that already pays (another tab, another administrator) is sent to the portal
        instead of paying twice."""
        tenant = self.sync_subscription(code, stripe)
        if tenant is None:
            raise ValueError("Negocio no encontrado.")
        if tenant["stripe_subscription"] and tenant["billing_status"] in LIVE:
            raise AlreadySubscribed("Ya tienes una suscripción. Gestiónala (tarjeta, facturas o baja) desde el portal "
                                    "de Stripe.")
        if not tenant["stripe_customer"]:
            customer = stripe.create_customer(tenant, email)
            with self._connect() as conn:
                self._billing_update(conn, code, {"stripe_customer": customer}, "")
            tenant = self.get(code)
        return stripe.checkout_url(tenant, email, success_url, cancel_url)

    def log(self, limit: int = 100) -> list[dict]:
        with self._connect() as conn:
            return conn.execute(f"SELECT happened_at, action, detail FROM {DIRECTORY_SCHEMA}.operator_log "
                                "ORDER BY id DESC LIMIT %s", (limit,)).fetchall()

    def close(self) -> None:
        release_pool(self._pool_key)

    # ------------------------------------------------------------- billing access
    def access_for(self, tenant: dict, stripe, checkout_session_id: str = "") -> tuple[Access, str, bool]:
        """What a business may do now, and a message for its visitor (or ""). Records a subscription just bought
        (`checkout_session_id`, when returning from Stripe Checkout) and re-checks with Stripe every SYNC_EVERY in
        case a webhook was lost. Full access while billing is off (`stripe` is None). The last value tells whether the
        directory was asked again (so cached copies of the business are stale)."""
        if stripe is None:
            return Access("full"), "", False
        message, refreshed = "", False
        if checkout_session_id:
            try:
                session = stripe.checkout_session(checkout_session_id)
                if session.get("client_reference_id") == tenant["code"] and isinstance(session.get("subscription"),
                                                                                       dict):
                    self.record_subscription(tenant["code"], session["subscription"], "suscripcion_contratada")
                    message = "¡Gracias! Tu suscripción está activa."
            except BillingError as exc:
                message = str(exc)
            tenant = self.get(tenant["code"]) or tenant
            refreshed = True
        synced = parse_when(tenant.get("billing_synced_at"))
        if tenant.get("stripe_customer") and (synced is None or utc_now() - synced > SYNC_EVERY):
            try:
                tenant = self.sync_subscription(tenant["code"], stripe) or tenant
                refreshed = True
            except BillingError:
                # Stripe unreachable: keep what we know and try again on a later visit (logged by billing).
                pass
        return access(tenant, utc_now()), message, refreshed

    def claim_operator_step(self, step: int) -> bool:
        """Accept an operator two-step code of time step `step` only if no later or equal one was accepted before,
        on any server and across restarts: the same code never opens the panel twice."""
        with self._connect() as conn:
            row = conn.execute(f"INSERT INTO {DIRECTORY_SCHEMA}.operator_totp(id, last_step) VALUES (1, %s) "
                               f"ON CONFLICT (id) DO UPDATE SET last_step = excluded.last_step "
                               f"WHERE {DIRECTORY_SCHEMA}.operator_totp.last_step < excluded.last_step RETURNING id",
                               (int(step),)).fetchone()
        return row is not None

    # ------------------------------------------------- operator sign-in throttle
    # The same policy as the businesses' sign-in (core/throttle.py), kept in the directory.
    def throttle_blocked_minutes(self, key: str, now: float | None = None) -> int:
        now = time.time() if now is None else now
        with self._connect() as conn:
            row = conn.execute(f"SELECT blocked_until FROM {DIRECTORY_SCHEMA}.login_throttle WHERE key = %s",
                               (key_hash(key),)).fetchone()
        return blocked_minutes(int(row["blocked_until"]), now) if row else 0

    def throttle_failed(self, key: str, now: float | None = None) -> None:
        now = time.time() if now is None else now
        hashed = key_hash(key)
        with self._connect() as conn:
            row = conn.execute(f"SELECT fails, blocked_until, level FROM {DIRECTORY_SCHEMA}.login_throttle "
                               "WHERE key = %s FOR UPDATE", (hashed,)).fetchone()
            fails, until, level = (json.loads(row["fails"]), row["blocked_until"], row["level"]) if row else ([], 0, 0)
            fails, until, level = after_failure(fails, until, level, now)
            if until > now and not fails:
                log.warning("operator_sign_in_blocked key=%s minutes=%s", hashed[:12], blocked_minutes(until, now))
            conn.execute(f"INSERT INTO {DIRECTORY_SCHEMA}.login_throttle(key, fails, blocked_until, level, updated) "
                         "VALUES (%s, %s, %s, %s, %s) ON CONFLICT (key) DO UPDATE SET fails = excluded.fails, "
                         "blocked_until = excluded.blocked_until, level = excluded.level, updated = excluded.updated",
                         (hashed, json.dumps([int(t) for t in fails]), int(until), level, int(now)))

    def throttle_succeeded(self, key: str) -> None:
        with self._connect() as conn:
            conn.execute(f"DELETE FROM {DIRECTORY_SCHEMA}.login_throttle WHERE key = %s", (key_hash(key),))

    def store(self, code: str) -> Store:
        tenant = self.get(code)
        if tenant is None:
            raise ValueError("Negocio no encontrado.")
        return Store(self._url, schema=tenant["schema_name"])



def businesses_in(url: str) -> list[tuple[str, str | None]]:
    """(code, schema) of each active business served by a database; [("", None)] for a single-business one.
    Only reads: unlike Directory, it never creates the directory."""
    import psycopg
    from psycopg.rows import dict_row

    with psycopg.connect(secure_url(url), row_factory=dict_row, connect_timeout=30) as conn:
        if not conn.execute("SELECT to_regclass(%s) AS t", (f"{DIRECTORY_SCHEMA}.tenants",)).fetchone()["t"]:
            return [("", None)]
        rows = conn.execute(f"SELECT code, schema_name FROM {DIRECTORY_SCHEMA}.tenants WHERE status = 'activo' "
                            "ORDER BY code").fetchall()
    return [(r["code"], r["schema_name"]) for r in rows]


def migrate_all(url: str) -> list[tuple[str, int]]:
    """Bring every business on a database up to this version's schema, before the app serves anyone: a change
    then fails at deploy time, in the log, instead of on some business's first visit. Returns (code, version)."""
    done = []
    for code, schema in businesses_in(url):
        store = Store(url, schema=schema)  # sets up or migrates the schema; a no-op when it is current
        try:
            done.append((code, store.schema_version()))
        finally:
            store.close()
    return done
